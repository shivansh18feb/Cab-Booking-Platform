package com.cab.booking.payment;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;

/**
 * Utility for verifying Razorpay payment and webhook HMAC-SHA256 signatures.
 * Employs constant-time byte comparison (MessageDigest.isEqual) to prevent timing attacks.
 */
public final class RazorpaySignatureUtil {

    private static final String HMAC_SHA256 = "HmacSHA256";

    private RazorpaySignatureUtil() {}

    /**
     * Verifies the checkout payment signature returned by Razorpay Checkout.
     * Payload expected by Razorpay: {@code orderId + "|" + paymentId}
     *
     * @param orderId   The Razorpay order ID (e.g. order_EKwxwAgItmmXdp)
     * @param paymentId The Razorpay payment ID (e.g. pay_EKwyeuyxbhcmms)
     * @param signature The signature generated by Razorpay Checkout
     * @param secret    The Razorpay Key Secret from server configuration
     * @return true if signature is valid and authentic; false otherwise
     */
    public static boolean verifyPaymentSignature(String orderId, String paymentId, String signature, String secret) {
        if (orderId == null || paymentId == null || signature == null || secret == null) {
            return false;
        }
        String data = orderId + "|" + paymentId;
        return verifyHmacSha256(data, signature, secret);
    }

    /**
     * Verifies the webhook signature against the raw request body.
     *
     * @param rawPayload The raw unparsed HTTP request body string
     * @param signature  The value of the X-Razorpay-Signature header
     * @param secret     The configured webhook secret
     * @return true if valid, false otherwise
     */
    public static boolean verifyWebhookSignature(String rawPayload, String signature, String secret) {
        if (rawPayload == null || signature == null || secret == null) {
            return false;
        }
        return verifyHmacSha256(rawPayload, signature, secret);
    }

    /**
     * Computes the HMAC-SHA256 hex digest of the given data and compares it in constant-time.
     */
    public static boolean verifyHmacSha256(String data, String signature, String secret) {
        try {
            Mac mac = Mac.getInstance(HMAC_SHA256);
            SecretKeySpec secretKeySpec = new SecretKeySpec(secret.getBytes(StandardCharsets.UTF_8), HMAC_SHA256);
            mac.init(secretKeySpec);
            byte[] hashBytes = mac.doFinal(data.getBytes(StandardCharsets.UTF_8));

            StringBuilder hex = new StringBuilder(hashBytes.length * 2);
            for (byte b : hashBytes) {
                int val = b & 0xff;
                if (val < 16) hex.append('0');
                hex.append(Integer.toHexString(val));
            }

            return MessageDigest.isEqual(
                    hex.toString().getBytes(StandardCharsets.UTF_8),
                    signature.trim().getBytes(StandardCharsets.UTF_8)
            );
        } catch (Exception ex) {
            return false;
        }
    }

    /**
     * Generates an HMAC-SHA256 hex signature for testing purposes.
     */
    public static String calculateSignature(String data, String secret) {
        try {
            Mac mac = Mac.getInstance(HMAC_SHA256);
            SecretKeySpec secretKeySpec = new SecretKeySpec(secret.getBytes(StandardCharsets.UTF_8), HMAC_SHA256);
            mac.init(secretKeySpec);
            byte[] hashBytes = mac.doFinal(data.getBytes(StandardCharsets.UTF_8));

            StringBuilder hex = new StringBuilder(hashBytes.length * 2);
            for (byte b : hashBytes) {
                int val = b & 0xff;
                if (val < 16) hex.append('0');
                hex.append(Integer.toHexString(val));
            }
            return hex.toString();
        } catch (Exception ex) {
            throw new RuntimeException("Failed to calculate HMAC-SHA256 signature", ex);
        }
    }
}
